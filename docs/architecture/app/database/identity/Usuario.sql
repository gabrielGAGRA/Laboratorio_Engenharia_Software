CREATE TABLE usuarios (
    usuario_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    spotify_id VARCHAR(64),
    nome_exibicao VARCHAR(150) NOT NULL,
    idade INT NOT NULL,
    plano_id INT NOT NULL,
    titular_id INT,
    generos_bloqueados TEXT,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuarios_plano 
        FOREIGN KEY (plano_id) REFERENCES planos (plano_id) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_usuarios_titular 
        FOREIGN KEY (titular_id) REFERENCES usuarios (usuario_id) 
        ON DELETE SET NULL,
    CONSTRAINT ck_usuarios_idade CHECK (idade >= 0),
    CONSTRAINT ck_usuarios_titular_diferente CHECK (titular_id IS NULL OR titular_id <> usuario_id)
);

-- E-mail único sem diferenciar maiúsculas de minúsculas
CREATE UNIQUE INDEX uq_usuarios_email ON usuarios (LOWER(email));
CREATE UNIQUE INDEX uq_usuarios_spotify_id ON usuarios (spotify_id) WHERE spotify_id IS NOT NULL;

-- Índices para Foreign Keys
CREATE INDEX idx_usuarios_plano ON usuarios (plano_id);
CREATE INDEX idx_usuarios_titular ON usuarios (titular_id);

-- Validação de limite de perfis vinculados ao titular
CREATE OR REPLACE FUNCTION valida_perfil_titular() RETURNS TRIGGER AS $$
DECLARE
    max_permitido INT;
    perfis_existentes INT;
BEGIN
    IF NEW.titular_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT p.max_perfis INTO max_permitido
    FROM usuarios t
    JOIN planos p ON p.plano_id = t.plano_id
    WHERE t.usuario_id = NEW.titular_id AND t.titular_id IS NULL;

    IF max_permitido IS NULL THEN
        RAISE EXCEPTION 'titular_id % nao e uma conta titular valida', NEW.titular_id;
    END IF;

    SELECT COUNT(*) INTO perfis_existentes
    FROM usuarios
    WHERE titular_id = NEW.titular_id AND usuario_id IS DISTINCT FROM NEW.usuario_id;

    -- +1 do titular, +1 do perfil sendo gravado
    IF perfis_existentes + 2 > max_permitido THEN
        RAISE EXCEPTION 'plano do titular % permite no maximo % perfis', NEW.titular_id, max_permitido;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuarios_valida_perfil
    BEFORE INSERT OR UPDATE OF titular_id ON usuarios
    FOR EACH ROW EXECUTE FUNCTION valida_perfil_titular();

CREATE TRIGGER trg_usuarios_atualizado_em
    BEFORE UPDATE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();
