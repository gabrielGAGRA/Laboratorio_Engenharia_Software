CREATE TABLE usuarios (
    usuario_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    spotify_id VARCHAR(64),
    nome_exibicao VARCHAR(150) NOT NULL,
    idade INT NOT NULL,
    plano_id INT NOT NULL,
    titular_id INT,
    generos_bloqueados JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuarios_plano 
        FOREIGN KEY (plano_id) REFERENCES planos (plano_id) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_usuarios_titular 
        FOREIGN KEY (titular_id) REFERENCES usuarios (usuario_id) 
        ON DELETE SET NULL
);

-- Aceleração de consultas em filtros JSONB (operadores @>, ?, ?|)
CREATE INDEX idx_usuarios_generos_bloqueados ON usuarios USING GIN (generos_bloqueados);
