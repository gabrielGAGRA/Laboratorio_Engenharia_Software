CREATE TABLE planos (
    plano_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    preco_mensal NUMERIC(10, 2) NOT NULL,
    max_perfis INT NOT NULL DEFAULT 1,
    CONSTRAINT ck_planos_preco CHECK (preco_mensal >= 0),
    CONSTRAINT ck_planos_max_perfis CHECK (max_perfis >= 1)
);
