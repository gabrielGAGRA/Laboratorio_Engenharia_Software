CREATE TABLE musicas (
    musica_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mbid UUID,
    isrc VARCHAR(12),
    spotify_id VARCHAR(64),
    titulo VARCHAR(255) NOT NULL,
    album_id INT,
    duracao_ms INT NOT NULL,
    pais CHAR(2),
    ano_lancamento INT,
    capa_url TEXT,
    itunes_preview_url TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_musicas_album
        FOREIGN KEY (album_id) REFERENCES albuns (album_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_musicas_duracao CHECK (duracao_ms > 0),
    CONSTRAINT ck_musicas_isrc CHECK (isrc ~ '^[A-Z]{2}[A-Z0-9]{3}[0-9]{7}$'),
    CONSTRAINT ck_musicas_pais CHECK (pais ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_musicas_ano CHECK (ano_lancamento BETWEEN 1900 AND 2100)
);

-- Identificadores externos únicos apenas entre músicas ativas (permite recadastrar após soft delete)
CREATE UNIQUE INDEX uq_musicas_isrc ON musicas (isrc) WHERE isrc IS NOT NULL AND NOT is_deleted;
CREATE UNIQUE INDEX uq_musicas_mbid ON musicas (mbid) WHERE mbid IS NOT NULL AND NOT is_deleted;
CREATE UNIQUE INDEX uq_musicas_spotify_id ON musicas (spotify_id) WHERE spotify_id IS NOT NULL AND NOT is_deleted;

CREATE INDEX idx_musicas_album ON musicas (album_id);
CREATE INDEX idx_musicas_titulo_trgm ON musicas USING GIN (titulo gin_trgm_ops);

CREATE TRIGGER trg_musicas_atualizado_em
    BEFORE UPDATE ON musicas
    FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();
