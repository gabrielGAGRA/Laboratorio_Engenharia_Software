CREATE TABLE jam_fila (
    jam_fila_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jam_id INT NOT NULL,
    musica_id INT NOT NULL,
    pontos_voto INT NOT NULL DEFAULT 0,
    adicionado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_jam_fila_jam 
        FOREIGN KEY (jam_id) REFERENCES jams (jam_id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_jam_fila_musica 
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id) 
        ON DELETE CASCADE
);

CREATE INDEX idx_jam_fila_jam_votos ON jam_fila (jam_id, pontos_voto DESC);
