CREATE TABLE jam_fila (
    jam_fila_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jam_id INT NOT NULL,
    musica_id INT NOT NULL,
    adicionado_por INT,
    status VARCHAR(10) NOT NULL DEFAULT 'pendente',
    pontos_voto INT NOT NULL DEFAULT 0,
    is_destaque BOOLEAN NOT NULL DEFAULT FALSE,
    adicionado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    iniciada_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_jam_fila_jam
        FOREIGN KEY (jam_id) REFERENCES jams (jam_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_jam_fila_musica
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_jam_fila_adicionado_por
        FOREIGN KEY (adicionado_por) REFERENCES usuarios (usuario_id)
        ON DELETE SET NULL,
    CONSTRAINT uq_jam_fila_musica UNIQUE (jam_id, musica_id),
    -- Alvo da FK composta dos votos de pular
    CONSTRAINT uq_jam_fila_jam UNIQUE (jam_fila_id, jam_id),
    CONSTRAINT ck_jam_fila_status CHECK (status IN ('pendente', 'tocando', 'tocada'))
);

-- Ordem da fila pendente: mais votos primeiro, desempate pelo mais antigo; destaque (superlike) tem prioridade na consulta
CREATE INDEX idx_jam_fila_pendentes ON jam_fila (jam_id, is_destaque DESC, pontos_voto DESC, adicionado_em)
    WHERE status = 'pendente';
-- No máximo uma música tocando por jam
CREATE UNIQUE INDEX uq_jam_fila_tocando ON jam_fila (jam_id) WHERE status = 'tocando';
CREATE INDEX idx_jam_fila_musica ON jam_fila (musica_id);
CREATE INDEX idx_jam_fila_adicionado_por ON jam_fila (adicionado_por);
