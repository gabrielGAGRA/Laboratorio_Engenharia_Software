CREATE TABLE playlist_musicas (
    playlist_musica_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id INT NOT NULL,
    musica_id INT NOT NULL,
    momento_id INT,
    posicao INT NOT NULL,
    adicionado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_playlist_musicas_playlist
        FOREIGN KEY (playlist_id) REFERENCES playlists (playlist_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_playlist_musicas_musica
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id)
        ON DELETE RESTRICT,
    -- FK composta: o momento precisa ser da mesma playlist; apagar o momento mantém a música na playlist
    CONSTRAINT fk_playlist_musicas_momento
        FOREIGN KEY (momento_id, playlist_id) REFERENCES playlist_momentos (momento_id, playlist_id)
        ON DELETE SET NULL (momento_id),
    CONSTRAINT uq_playlist_musica UNIQUE (playlist_id, musica_id),
    -- Adiada até o commit para permitir reordenar dentro de uma transação
    CONSTRAINT uq_playlist_musicas_posicao UNIQUE (playlist_id, posicao) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX idx_playlist_musicas_musica ON playlist_musicas (musica_id);
CREATE INDEX idx_playlist_musicas_momento ON playlist_musicas (momento_id);
