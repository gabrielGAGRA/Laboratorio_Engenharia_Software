CREATE TABLE avaliacoes_comentarios (
    avaliacao_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    musica_id INT NOT NULL,
    nota INT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    texto TEXT,
    likes_count INT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_avaliacoes_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuarios (usuario_id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_avaliacoes_musica 
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id) 
        ON DELETE CASCADE
);

CREATE INDEX idx_avaliacoes_musica ON avaliacoes_comentarios (musica_id);
