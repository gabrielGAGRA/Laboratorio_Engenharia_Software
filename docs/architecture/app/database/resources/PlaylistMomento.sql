-- Blocos de uma playlist de evento, cada um com duração e gênero próprios
CREATE TABLE playlist_momentos (
    momento_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id INT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    posicao INT NOT NULL,
    duracao_alvo_ms INT,
    genero_id INT,
    CONSTRAINT fk_playlist_momentos_playlist
        FOREIGN KEY (playlist_id) REFERENCES playlists (playlist_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_playlist_momentos_genero
        FOREIGN KEY (genero_id) REFERENCES generos (genero_id)
        ON DELETE SET NULL,
    -- Alvo da FK composta de playlist_musicas (garante que o momento pertence à mesma playlist)
    CONSTRAINT uq_playlist_momentos_playlist UNIQUE (momento_id, playlist_id),
    CONSTRAINT uq_playlist_momentos_posicao UNIQUE (playlist_id, posicao) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_playlist_momentos_duracao CHECK (duracao_alvo_ms IS NULL OR duracao_alvo_ms > 0)
);

CREATE INDEX idx_playlist_momentos_genero ON playlist_momentos (genero_id);
