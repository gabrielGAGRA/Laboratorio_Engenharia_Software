CREATE TABLE interacoes (
    Interaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    musica_id INT NOT NULL,
    acao VARCHAR(50) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interacoes_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuarios (usuario_id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_interacoes_musica 
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id) 
        ON DELETE RESTRICT,
    CONSTRAINT ck_interacoes_acao 
        CHECK (acao IN ('like', 'superlike', 'rejeitar')),
    CONSTRAINT uq_interacoes_usuario_musica 
        UNIQUE (usuario_id, musica_id)
);

-- Índices de consulta e FK
CREATE INDEX idx_interacoes_musica ON interacoes (musica_id);
CREATE INDEX idx_interacoes_usuario_criado ON interacoes (usuario_id, criado_em DESC);
