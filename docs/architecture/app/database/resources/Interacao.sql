-- Swipes (like, superlike, rejeitar) são estado: no máximo um por usuário e música; "desfazer" = DELETE,
-- trocar de opinião = UPDATE. Reproduções são eventos e podem se repetir.
-- Curtidas = like + superlike; Amadas = superlike (derivados por consulta).
CREATE TABLE interacoes (
    interacao_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    musica_id INT NOT NULL,
    acao VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interacoes_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (usuario_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_interacoes_musica
        FOREIGN KEY (musica_id) REFERENCES musicas (musica_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_interacoes_acao CHECK (acao IN ('like', 'superlike', 'rejeitar', 'reproducao'))
);

-- Um swipe por usuário/música; também serve de índice para "músicas já avaliadas" no feed
CREATE UNIQUE INDEX uq_interacoes_swipe ON interacoes (usuario_id, musica_id) WHERE acao <> 'reproducao';
-- "Desfazer": último swipe do usuário
CREATE INDEX idx_interacoes_ultimo_swipe ON interacoes (usuario_id, criado_em DESC) WHERE acao <> 'reproducao';
-- Dashboard: acessos por música e FK
CREATE INDEX idx_interacoes_musica ON interacoes (musica_id, acao);
